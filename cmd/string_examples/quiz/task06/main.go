package main

import (
	"fmt"
	"runtime"
)

// ВОПРОС: Удерживает ли подстрока sub весь массив big (1 МБ)
// в памяти после того, как big и s освобождены?
// Ответ: Да, sub будет удерживать весь исходный массив байт
// срез строки не копирует данные, а создаёт новую строку,
// ссылающуюся на ту же область памяти.
func main() {
	big := make([]byte, 1<<20) // 1 MB
	for i := range big {
		big[i] = 'a'
	}
	s := string(big)
	sub := s[:10] // берём первые 10 байт

	// Освобождаем big, но s и sub живы
	big = nil
	s = "" // на самом деле s всё ещё ссылается на память через sub? Нет, но sub ссылается на ту же память.
	// Убедимся, что sub удерживает память
	runtime.GC()
	// Для демонстрации можно вывести размер памяти, но здесь просто вопрос.
	fmt.Println(sub)
}
