// Префиксные ПРОИЗВЕДЕНИЯ — та же идея, что и суммы, но в обе
// стороны (LeetCode 238 Product of Array Except Self).
//
// result[i] = product(все nums, кроме nums[i])
//
//	= (произведение ВСЁГО слева от i) × (произведение ВСЁГО
//	  справа от i).
//
// Левая половина — бегущий product слева направо, правая —
// накопительный product справа налево. Без деления (условие запрещает),
// за O(n) времени и O(1) доп. памяти (выходной массив не считается).
package main

// ProductExceptSelf — произведения всех элементов, кроме своего
// индекса.
//
// Пример: [1,2,3,4] -> [24,12,8,6].
func ProductExceptSelf(nums []int) []int {
	n := len(nums)
	result := make([]int, n)

	// Произведение всего, что СЛЕВА (для i=0 — 1, «пустое»).
	left := 1
	for i := 0; i < n; i++ {
		result[i] = left
		left *= nums[i]
	}
	// Умножаем на произведение ВСЁ, что СПРАВА, справа налево.
	right := 1
	for i := n - 1; i >= 0; i-- {
		result[i] *= right
		right *= nums[i]
	}
	return result
}
