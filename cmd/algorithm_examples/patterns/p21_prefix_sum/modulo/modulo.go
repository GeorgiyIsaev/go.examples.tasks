// Префиксные суммы ПО МОДУЛЮ — продвинутая форма паттерна.
//
// Ключевая идея: для «сумма подмассива делится на k» / «равное
// количество 0 и 1» важно не значение суммы, а её ОСТАТОК
// (конгруэнтность). Тогда:
//
//	sum(i..j) ≡ 0 (mod k)  ⇔  prefix[j+1] ≡ prefix[i] (mod k)
//
// и задача превращается в «сколько раз остаток уже встречался» —
// карта счётчика остатков, как в p05/pairs (LC560), только вместо
// разности — равенство остатков.
//
// Сложность: один проход + map — O(n) время, O(k) память
// (остатков не больше k).

// SubarraySumDivByK — число непрерывных подмассивов, чья сумма
// делится на k (LeetCode 974).
//
// Отрицательные остатки приводим к [0, k): в Go `%` отрицателен,
// поэтому `(sum%k + k) % k`.
//
// Пример: [4,5,0,-2,-3,1], k=5 -> 7.
func SubarraySumDivByK(nums []int, k int) int {
	count := map[int]int{0: 1} // пустой префикс, остаток 0
	sum := 0
	result := 0
	for _, x := range nums {
		sum += x
		rem := ((sum % k) + k) % k // остаток в [0, k)
		// Каждый прежний такой остаток даёт подмассив с суммой %k == 0.
		result += count[rem]
		count[rem]++
	}
	return result
}

// FindMaxLength — самая длинная непрерывная подмассив с РАВНЫМ
// количеством 0 и 1 (LeetCode 525).
//
// Трюк: 1 считаем +1, 0 считаем −1; равные количества ⇔ сумма 0.
// Значит: «prefix-сумма уже встречалась» — первый индекс встречи
// и есть самая длинная пара.
//
// Пример: [0,1] -> 2; [0,1,0] -> 2.
func FindMaxLength(nums []int) int {
	firstSeen := map[int]int{0: -1} // остаток 0 «был» до начала
	sum := 0
	best := 0
	for i, v := range nums {
		if v == 1 {
			sum++
		} else {
			sum--
		}
		if j, ok := firstSeen[sum]; ok {
			if i-j > best {
				best = i - j
			}
		} else {
			firstSeen[sum] = i // только первое появление!
		}
	}
	return best
}
