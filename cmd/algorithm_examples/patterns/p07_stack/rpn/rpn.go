package main

import (
	"strconv"
)

// Обратная польская нотация (ОПН, RPN) и вычисление выражений.
//
// RPN — нотация без скобок и приоритетов: операнды идут вперёд,
// оператор — после, «к чему применить» всегда видно по двум последним
// числам на стеке. Отсюда вычисление тривиально:
//
//	токен-число      -> положить в стек;
//	токен-оператор   -> снять два, применить, положить результат.
//
// Обратная сторона той же идеи — инфиксная запись «a + b * c»:
// стек операторов (shunting-yard) держит отложенные операторы
// по приоритету. Здесь — вариант «с приоритетами, но без скобок»
// (Basic Calculator II, LeetCode 227).
//
// Сложность обоих: O(n) времени, O(n) памяти.

// EvalRPN — вычислить выражение в обратной польской нотации
// (LeetCode 150).
// Токены: числа и "+", "-", "*", "/". Деление — округление к нулю
// (в Go целочисленное деление уже такое).
//
// Пример: ["2","1","+","3","*"] -> 9;  ["4","13","5","/","+"] -> 6.
func EvalRPN(tokens []string) int {
	stack := make([]int, 0, len(tokens))

	for _, tok := range tokens {
		if v, err := strconv.Atoi(tok); err == nil {
			stack = append(stack, v)
			continue
		}
		// Оператор: снимаем b (верхний), затем a.
		b := stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		a := stack[len(stack)-1]
		stack = stack[:len(stack)-1]

		var res int
		switch tok {
		case "+":
			res = a + b
		case "-":
			res = a - b
		case "*":
			res = a * b
		case "/":
			res = a / b // деление к нулю, деление на 0 не по условию
		}
		stack = append(stack, res)
	}
	return stack[0]
}

// CalcStringII — вычислить инфиксное выражение с +, -, *, / и без
// скобок (LeetCode 227). Числа неотрицательные, пробелы есть.
//
// Идея: однопроходный стек «отложенных операций».
//   - Накопляем число.
//   - Встретили '+'/'-': предыдущее число уже не зависит от следующих
//     операторов — можно «закрыть» его: сложить/вычесть сразу
//     (через '0', чтобы минус работал).
//   - Встретили '*'/'-': предыдущее число ДОПОЛНИТЕЛЬНО умножается
//     на следующее — нельзя закрывать сразу, откладываем.
//   - В конце прибавляем все отложенные куски.
//
// Пример: "3+2*2" -> 7; " 3/2 " -> 1; " 3+5 / 2 " -> 5.
func CalcStringII(s string) int {
	stack := []int{}
	num := 0
	prev := byte('+') // последний встреченный оператор

	flush := func(op byte, val int) {
		switch op {
		case '+':
			stack = append(stack, val)
		case '-':
			stack = append(stack, -val)
		case '*':
			stack[len(stack)-1] *= val
		case '/':
			stack[len(stack)-1] /= val
		}
	}

	for i := 0; i <= len(s); i++ {
		var c byte
		if i < len(s) {
			c = s[i]
		}
		if c >= '0' && c <= '9' {
			num = num*10 + int(c-'0')
			continue
		}
		if c == ' ' && i < len(s) {
			continue
		}
		// Любой оператор или конец строки: закрываем число.
		flush(prev, num)
		if i < len(s) {
			prev = c
		}
		num = 0
	}

	total := 0
	for _, v := range stack {
		total += v
	}
	return total
}
