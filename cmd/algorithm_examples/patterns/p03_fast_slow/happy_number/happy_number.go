package main

// Паттерн: Floyd's cycle detection на ЧИСЛАХ, а не на списке.
//
// Идея: любая задача, где состояние детерминировано (next(x) всегда
// один и тот же), сводится к обходу цепочки. Цепочка либо приходит
// в 1 (happy), либо зацикливается. Цикл ловим двумя указателями
// с разной скоростью — без map и без O(n) памяти.
//
// Сложность: O(n) время (число шагов до встречи), O(1) память.

// IsHappy — является ли число «счастливым».
// Счастливое число: сумма квадратов цифр, потом снова, и так пока
// не получим 1 (счастливое) или не зациклимся (несчастливое).
//
// Пример: 19 -> true (1+81=82, 64+4=68, 36+64=100, 1+0+0=1).
//
//	2  -> false (зациклится на 4-16-37-58-89-145-42-20-4).
func IsHappy(n int) bool {
	next := func(x int) int {
		sum := 0
		for x > 0 {
			d := x % 10
			sum += d * d
			x /= 10
		}
		return sum
	}

	slow, fast := n, n
	for {
		slow = next(slow)
		fast = next(next(fast))
		if slow == fast {
			break
		}
	}
	// В отличие от поиска входа в цикл, здесь цикл может быть длиной 1
	// (само число зациклилось), поэтому проверяем значение, а не позицию.
	return slow == 1
}
