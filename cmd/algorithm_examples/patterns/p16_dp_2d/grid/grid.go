package main

// Паттерн: DP по сетке (двумерное состояние).
//
// Клетка (i, j) достижима/лучше ТОЛЬКО из (i-1, j) и (i, j-1) —
// значит, двумерная таблица заполняется сверху-слева направо-вниз,
// и рекуррентность выглядит как «сумма/минимум двух клеток слева».
//
//	dp[i][j] = f(dp[i-1][j], dp[i][j-1], вес клетки)
//
// База — первая строка и первый столбец (или одномерный ряд).
// Сложность: O(m·n) время, O(m·n) память; при необходимости —
// O(n) на один ряд (см. замечания в коде).

// UniquePaths — число путей робота из (0,0) в (m-1, n-1), движение
// только вправо и вниз (LeetCode 62).
//
// dp[i][j] = dp[i-1][j] + dp[i][j-1], база — первая строка/столбец = 1.
//
// Пример: m=3, n=7 -> 28.
func UniquePaths(m, n int) int {
	// Одномерный ряд: dp[j] — количество путей до клетки текущей
	// строки, столбца j. Обновляется слева направо: dp[j] (сверху)
	// ещё не тронуто, dp[j-1] — уже текущая строка (слева).
	dp := make([]int, n)
	for j := range dp {
		dp[j] = 1 // первая строка
	}
	for i := 1; i < m; i++ {
		for j := 1; j < n; j++ {
			dp[j] += dp[j-1] // dp[j] (сверху) + dp[j-1] (слева)
		}
	}
	return dp[n-1]
}

// MinPathSum — минимальная сумма пути из (0,0) в (m-1, n-1)
// (движение только вправо и вниз, LeetCode 64).
//
// dp[i][j] = grid[i][j] + min(dp[i-1][j], dp[i][j-1]).
// Первая строка и столбец — накопительные суммы (идти можно
// только вдоль них).
//
// Пример: [[1,3,1],[1,5,1],[4,2,1]] -> 7 (1→3→1→1→1).
func MinPathSum(grid [][]int) int {
	if len(grid) == 0 || len(grid[0]) == 0 {
		return 0
	}
	m, n := len(grid), len(grid[0])
	dp := make([]int, n)

	// Первая строка: только вправо.
	dp[0] = grid[0][0]
	for j := 1; j < n; j++ {
		dp[j] = dp[j-1] + grid[0][j]
	}

	for i := 1; i < m; i++ {
		dp[0] += grid[i][0] // первый столбец: только вниз
		for j := 1; j < n; j++ {
			if dp[j] < dp[j-1] {
				dp[j] = grid[i][j] + dp[j] // сверху дешевле
			} else {
				dp[j] = grid[i][j] + dp[j-1] // слева дешевле
			}
		}
	}
	return dp[n-1]
}
