package main

// Паттерн: хэш-мапа как «индекс/память о том, что уже видели».
//
// Ключевая идея: перебор пар в лоб — O(n²). Мапа превращает второй
// проход в «достань нужного напарника за O(1)»:
//
//	видя x, спрашиваем: встречался ли target - x?  ->  O(1)
//
// Так решаются Two Sum и все его вариации (пара, тройка через пару,
// разница двух чисел, «равные суммы префиксов»).

// TwoSum — индексы двух чисел с суммой target (LeetCode 1).
// Ровно одна пара по условию; индексы i < j.
//
// Трюк: один проход — в мапе лежат уже ПРОЙДЕННЫЕ значения, так что
// j всегда больше i: пары не «переворачиваются».
//
// Пример: [2,7,11,15], 9 -> [0,1].
func TwoSum(nums []int, target int) []int {
	seen := map[int]int{} // значение -> его индекс
	for j, x := range nums {
		if i, ok := seen[target-x]; ok {
			return []int{i, j}
		}
		seen[x] = j
	}
	return []int{}
}

// TwoSumCount — сколько ПАЙРОВ ИНДЕКСОВ (i < j) дают сумму target.
// Учитываются все позиции, включая дубли значений.
//
// Пример: [1,1,1], 2 -> 3 пары (0-1, 0-2, 1-2).
func TwoSumCount(nums []int, target int) int {
	count := 0
	seen := map[int]int{} // значение -> сколько раз встречено
	for _, x := range nums {
		// Каждый уже встреченный (target - x) даёт ровно одну пару
		// с текущей позицией x.
		count += seen[target-x]
		seen[x]++
	}
	return count
}

// SubarraySum — количество непрерывных подмассивов с суммой k
// (LeetCode 560): префиксные суммы + мапа счётчика.
//
// Идея: sum(i..j) == prefix[j] - prefix[i-1] == k  =>
// ищем, сколько раз встречалась prefix[j] - k.
// Счётчик важен: одинаковых префиксов может быть несколько
// (например, нули в хвосте).
//
// Пример: [1,1,1], k=2 -> 2 ([1,1] на позициях 0-1 и 1-2).
func SubarraySum(nums []int, k int) int {
	prefixCount := map[int]int{0: 1} // пустой префикс суммы 0
	prefix := 0
	count := 0
	for _, x := range nums {
		prefix += x
		count += prefixCount[prefix-k]
		prefixCount[prefix]++
	}
	return count
}
