// Паттерн: DP по одномерному массиву.
//
// Общая схема любой DP-задачи:
//  1. **Определить состояние** — dp[i] = «оптимум для префикса длины i»
//     (или «до ступеньки i»). Чем точнее ответишь на вопрос
//     «что означает dp[i]», тем проще рекуррентность.
//  2. **Рекуррентность** — dp[i] = f(dp[i-1], dp[i-2], ..., вход).
//  3. **База** — dp[0], dp[1] (или просто «по умолчанию»).
//  4. **Ответ** — обычно dp[n-1] или max по массиву.
//
// Переход по 1-2 «предыдущим позициям» => можно хранить всего
// переменные prev/curr вместо массива: память O(1).
//
// Обе задачи ниже — «Фибоначчи с весами».

// ClimbStairs — сколько способов добраться до n-й ступеньки,
// шагая по 1 или 2 (LeetCode 70).
//
// dp[i] = dp[i-1] + dp[i-2]: последний шаг либо с (i-1), либо с (i-2).
// База: dp[1] = 1, dp[2] = 2. Это ровно числа Фибоначчи.
//
// Пример: n=3 -> 3 ([1,1,1], [1,2], [2,1]).
func ClimbStairs(n int) int {
	if n <= 2 {
		if n <= 0 {
			return 0
		}
		return n
	}
	prev2, prev1 := 1, 2 // dp[1], dp[2]
	for i := 3; i <= n; i++ {
		prev2, prev1 = prev1, prev1+prev2
	}
	return prev1
}

// MinCostClimbingStairs — минимальная стоимость, чтобы добраться
// до вершины (LeetCode 746). Стоимость — на КАЖДОЙ ступеньке,
// дойдя до вершины, платить не надо.
//
// dp[i] — минимальная стоимость, чтобы встать на ступеньку i:
// dp[i] = min(dp[i-1] + cost[i-1], dp[i-2] + cost[i-2]).
// Ответ: dp[len(cost)] — «вершина» как отдельная позиция.
//
// Пример: [10,15,20] -> 15 (встать на 1-ю ступень бесплатно,
// прыгнуть через 20: dp = [0,0,10,15]).
func MinCostClimbingStairs(cost []int) int {
	n := len(cost)
	if n <= 1 {
		return 0
	}
	// dp[i] — минимальная стоимость оказаться на ступеньке i.
	dp := make([]int, n+1)
	for i := 2; i <= n; i++ {
		fromPrev := dp[i-1] + cost[i-1]
		fromPrev2 := dp[i-2] + cost[i-2]
		if fromPrev < fromPrev2 {
			dp[i] = fromPrev
		} else {
			dp[i] = fromPrev2
		}
	}
	return dp[n]
}
