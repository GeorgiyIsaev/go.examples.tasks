package main

// Interval List Intersections (LeetCode 986): пересечение двух списков
// отрезков, каждый список отсортирован и не содержит пересечений.
//
// Идея: ДВА указателя, как в merge у сортировки слиянием:
//   - смотрим пару (A[i], B[j]);
//   - точка пересечения = [max(start), min(end)];
//   - она непуста, если max(start) <= min(end) — добавляем;
//   - отрезок с МЕНЬШИМ концом точно исчерпан (дальше в нём ничего
//     не совпадёт с текущим концом другого) — двигаем его указатель.
//
// Сложность: O(n + m) время, O(1) сверх ответа (оба входа уже
// отсортированы — сортировать не надо!).
//
// Пример: [[0,2],[5,10],[13,15],[16,18]] ∩ [[1,5],[8,12],[15,24]]
//   -> [[1,2],[5,5],[8,10],[15,15],[16,18]].

// IntervalIntersection возвращает список пересечений двух наборов
// отрезков.
func IntervalIntersection(first, second [][]int) [][]int {
	result := [][]int{}
	i, j := 0, 0

	for i < len(first) && j < len(second) {
		lo := max(first[i][0], second[j][0])
		hi := min(first[i][1], second[j][1])

		if lo <= hi { // пересечение есть (касание — точка)
			result = append(result, []int{lo, hi})
		}
		// Двигаем тот отрезок, который кончается раньше.
		if first[i][1] < second[j][1] {
			i++
		} else {
			j++
		}
	}
	return result
}
