package main

// Паттерн: битовые операции (bit manipulation).
//
// Базовая таблица, которую надо знать наизусть:
//
//	x & (x-1)   — снимает МЛАДШИЙ установленный бит (самый частый трюк);
//	x & -x       — выделяет МЛАДШИЙ установленный бит (в Go: x & (^x+1));
//	x & 1        — проверка чётности / младший бит;
//	x >> 1       — сдвиг вправо = деление на 2 (для uint/без знака);
//	x ^ x = 0, x ^ 0 = x — свойства XOR;
//	~x = -x - 1  — инверсия.
//
// Go-специфика: `int` знаковый, сдвиги и >> работают, но результат
// >> на отрицательных — арифметический (с заполнением знаком).
// Для битовых задач честнее работать через uint32/uint64.
//
// Сложность: O(number of bits) = O(1) на 32/64-битных числах.

// HammingWeight — число единичных бит (LeetCode 191).
// Хак `x & (x-1)` убирает по одному биту за итерацию —
// итераций ровно столько, сколько единиц.
//
// Пример: 11 (1011) -> 3.
func HammingWeight(n uint32) int {
	count := 0
	for n != 0 {
		n &= n - 1 // снять младшую единицу
		count++
	}
	return count
}

// IsPowerOfTwo — является ли n степенью двойки (LeetCode 231).
// У степеней двойки ровно ОДНА единица => n & (n-1) == 0.
// 0 — не степень двойки.
//
// Пример: 16 -> true, 18 -> false, 0 -> false.
func IsPowerOfTwo(n int) bool {
	if n <= 0 {
		return false
	}
	return n&(n-1) == 0
}

// CountBits — для каждого i от 0 до n число единиц в его записи
// (LeetCode 338).
//
// Формула DP + биты: bits[i] = bits[i>>1] + (i&1) —
// «число единиц без младшего бита + сам младший бит».
// (Альтернатива: bits[i] = bits[i&(i-1)] + 1 — снимаем младшую
// единицу; обе O(n).)
//
// Пример: n=2 -> [0,1,1].
func CountBits(n int) []int {
	bits := make([]int, n+1)
	for i := 1; i <= n; i++ {
		bits[i] = bits[i>>1] + (i & 1)
	}
	return bits
}
