package main

// XOR-семейство — «магия одной операции».
//
// Свойства XOR, на которых всё держится:
//
//	a ^ a = 0     (погашение одинаковых)
//	a ^ 0 = a     (нейтральный элемент)
//	коммутативность и ассоциативность => порядок не важен
//
// Главный шаблон: «xor всех элементов» гасит пары и оставляет
// то, что встречается НЕЧЁТНО (один раз). Дальше — вариации на
// «отделить искру от пепла» битовыми масками.

// SingleNumber — каждый элемент встречается дважды, кроме одного;
// найти его (LeetCode 136).
//
// Пример: [4,1,2,1,2] -> 4.
func SingleNumber(nums []int) int {
	acc := 0
	for _, v := range nums {
		acc ^= v // пары гасятся, одиночная остаётся
	}
	return acc
}

// SingleNumberII — каждый встречается ТРИжды, кроме одного
// (LeetCode 137).
//
// Идея: два аккумулятора ones/twos — для КАЖДОГО бита они кодируют
// встречаемость mod 3: 00 -> 0 раз, 10 -> 1 раз, 01 -> 2 раза.
// После n проходов в ones останутся биты числа-одиночки.
//
// Пример: [2,2,3,2] -> 3.
func SingleNumberII(nums []int) int {
	ones, twos := 0, 0
	for _, v := range nums {
		// Новый порядок: сначала обновляем ones, потом twos —
		// и каждый сбрасывает то, что уже счело «тройку».
		ones = (ones ^ v) & ^twos
		twos = (twos ^ v) & ^ones
	}
	return ones
}

// SingleNumberIII — все элементы встречаются дважды, кроме ДВУХ
// одиночек; найти обе (LeetCode 260).
//
// Идея: xor всех даёт a ^ b (одиночки схлопнулись, пары — в 0).
// Взять любой установленный бит (x & -x): a и b различаются в нём
// — делим все числа на две группы по этому биту и ищем одиночку
// в каждой (как LC136).
//
// Пример: [1,2,1,3,2,5] -> [3,5].
func SingleNumberIII(nums []int) []int {
	xor := 0
	for _, v := range nums {
		xor ^= v // = a ^ b, а != 0
	}
	// Младший различающийся бит: xor & (-xor) в дополнительном коде.
	diff := xor & -xor

	a := 0
	for _, v := range nums {
		if v&diff != 0 {
			a ^= v // группа с этим битом
		}
	}
	return []int{a, xor ^ a}
}
