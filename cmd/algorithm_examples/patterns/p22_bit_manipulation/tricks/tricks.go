// Трюки на битах: расстояние Хэмминга, реверс битов и сложение
// без «+».
//
// Здесь применяется база из basics/ в задачах посложнее:
//   - отдельные биты обрабатываются независимо => XOR для сравнения;
//   - «снимаем младшую единицу» x&(x-1) для подсчётов;
//   - carry (перенос) считаем через &, сдвигаем через << —
//     это и есть сумматор в миниатюре.
package main

// HammingDistance — число позиций, где биты a и b различны
// (LeetCode 461). Равносильно popcount(a ^ b).
//
// Пример: a=1 (0001), b=4 (0100) -> 2.
func HammingDistance(a, b int) int {
	return popCount(uint64(a ^ b))
}

// ReverseBits — развернуть 32 бита задом наперёд (LeetCode 190).
// Пример: 00000010100101000001111010011100 -> ...11001100... (см. тест).
//
// Сдвигаем результат вправо и «наращиваем» бит из x слева:
// за 32 итерации младший бит x становится старшим и наоборот.
func ReverseBits(x uint32) uint32 {
	var result uint32
	for i := 0; i < 32; i++ {
		result = (result << 1) | (x & 1)
		x >>= 1
	}
	return result
}

// GetSum — сложить два числа БЕЗ оператора «+» (LeetCode 371).
// Сумма = сложение без переноса (XOR) + перенос (AND со сдвигом);
// перенос сдвигается, пока не станет нулём.
//
// Пример: 5 + 7 = 12: 5^7=2, (5&7)<<1=10, 2^10=8, 20... (см. тесты).
func GetSum(a, b int) int {
	for b != 0 {
		carry := (a & b) << 1 // биты переноса
		a = a ^ b             // сложение без переноса
		b = carry
	}
	return a
}

// popCount — число единиц в 64-битном представлении (трюк x&(x-1)).
func popCount(x uint64) int {
	count := 0
	for x != 0 {
		x &= x - 1
		count++
	}
	return count
}
