// Две «жемчужины» монотонного стека — задачи, где лобовое O(n²)
// заменяется на O(n) одним стеком.
//
// 1. Trapping Rain Water (LeetCode 42) — сколько воды поместится
//    между столбиками. Здесь стек хранит ИНДЕКСЫ по возрастанию
//    высот: встретив более высокий столбик, «закрываем» лужу,
//    вычисляя её дно по паре «левый край — низ — правый край».
//
// 2. Largest Rectangle in Histogram (LeetCode 84) — максимальная
//    площадь прямоугольника. Стек хранит индексы по возрастанию высот;
//    встретив меньшую высоту — прямоугольник с высотой вершины
//    стека закрыт, его ширина — от предыдущего «меньшего» слева
//    до текущего справа.
//
// Сложность обоих: O(n) время, O(n) память.

// Trap — сколько воды удерживается высотами (LeetCode 42).
//
// Идея со стеком (по слоям): стек — индексы столбиков с НЕубывающими
// высотами. Как только новый столбик выше вершины — нашли «дно»:
//   - bottom = высота вершины после pop (настоящее дно лужи);
//   - left   = новая вершина (левый край);
//   - right  = текущий индекс (правый край);
//   - ширина = right - left - 1, глубина = min(h[left], h[right]) - hbottom;
//   - вода += ширина × глубина.
//
// Пример: [0,1,0,2,1,0,1,3,2,1,2,1] -> 6.
func Trap(heights []int) int {
	stack := []int{} // индексы, высоты по возрастанию
	water := 0

	for i := 0; i < len(heights); i++ {
		for len(stack) > 0 && heights[i] > heights[stack[len(stack)-1]] {
			bottom := stack[len(stack)-1]
			stack = stack[:len(stack)-1]
			if len(stack) == 0 {
				break // левого края нет — воды нет
			}
			left := stack[len(stack)-1]
			width := i - left - 1
			depth := min(heights[i], heights[left]) - heights[bottom]
			water += width * depth
		}
		stack = append(stack, i)
	}
	return water
}

// LargestRectangleArea — максимальная площадь прямоугольника
// в гистограмме (LeetCode 84).
//
// Идея: для каждого столбика как «самой низкой полосы» найти,
// насколько он тянется влево-вправо, пока соседи не ниже. Стек
// по возрастанию высот даёт это за O(n):
//   - встретил меньшую высоту — вершина стека больше не может
//     тянуться вправо, её граница справа = i;
//     граница слева = индекс под новой вершиной стека (или -1).
//
// Пример: [2,1,5,6,2,3] -> 10 (прямоугольник высотой 5 ширины 2).
func LargestRectangleArea(heights []int) int {
	stack := []int{} // индексы, высоты по возрастанию
	maxArea := 0

	// +1 справа — чтобы «закрыть» все оставшиеся столбики после цикла.
	for i := 0; i <= len(heights); i++ {
		cur := 0 // за пределами массива высота 0 — закрывает всё
		if i < len(heights) {
			cur = heights[i]
		}
		for len(stack) > 0 && cur < heights[stack[len(stack)-1]] {
			h := heights[stack[len(stack)-1]]
			stack = stack[:len(stack)-1]
			width := i
			if len(stack) > 0 {
				width = i - stack[len(stack)-1] - 1
			}
			if area := h * width; area > maxArea {
				maxArea = area
			}
		}
		stack = append(stack, i)
	}
	return maxArea
}
