// Жадность на потоке данных: «купил-продал» (LeetCode 121 и 122).
//
// Обе задачи решаются ОДНИМ проходом с инвариантом «жадного
// наблюдателя»:
//   - одна сделка: держим минимум цены покупки, на каждой цене
//     считаем прибыль от продажи сейчас и обновляем максимум;
//   - бесконечно сделок: фиксируем КАЖДЫЙ положительный рост —
//     sum of all upticks. Почему это оптимально: любой участок
//     роста a -> b разбивается на ряд единичных шагов, и их сумма
//     равна b - a; не брать рост = бросить деньги.
//
// Сложность: O(n) время, O(1) память.
// Сигнал «это greedy, а не DP»: ответ — одно число из одного прохода,
// и нет таблицы «до позиции i».

package main

// MaxProfit — максимум прибыли с одной сделкой (купить раньше,
// продать позже; LeetCode 121).
//
// Пример: [7,1,5,3,6,4] -> 5 (купить по 1, продать по 6).
func MaxProfit(prices []int) int {
	if len(prices) == 0 {
		return 0
	}
	minPrice := prices[0]
	best := 0
	for _, p := range prices[1:] {
		if p-minPrice > best {
			best = p - minPrice
		}
		if p < minPrice {
			minPrice = p
		}
	}
	return best
}

// MaxProfitMany — максимум прибыли с неограниченным числом сделок
// (купил — сразу можешь продать; LeetCode 122).
//
// Суммируем каждый положительный прирост цены между соседними днями.
//
// Пример: [7,1,5,3,6,4] -> 7 (1->5: 4, 3->6: 3).
func MaxProfitMany(prices []int) int {
	profit := 0
	for i := 1; i < len(prices); i++ {
		if prices[i] > prices[i-1] {
			profit += prices[i] - prices[i-1]
		}
	}
	return profit
}
