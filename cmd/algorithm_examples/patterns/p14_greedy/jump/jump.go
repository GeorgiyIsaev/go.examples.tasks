package main

// Паттерн: жадность (greedy).
//
// Идея: на каждом шаге выбираем ЛУЧШИЙ локальный вариант и не
// возвращаемся к нему — потому что доказано (или видно из условия),
// что локально лучшее ведёт к глобальному оптимуму. Дешевле DP:
// O(n)-проход, O(1) память. Но опаснее: нужен аргумент «почему
// локальное = глобальное».
//
// Jump Game — семейство задач, где инвариант — «дальше всех
// ДОСТИЖИМ» (reach).

// CanJump — можно ли добраться до последнего индекса (LeetCode 55):
// из i можно прыгнуть на 0..nums[i] вперёд.
//
// Жадный инвариант: reach — самый дальний достижимый индекс.
// Если текущий индекс дальше reach — недостижим, false.
// Конец: reach >= n-1.
//
// Пример: [2,3,1,1,4] -> true; [3,2,1,0,4] -> false.
func CanJump(nums []int) bool {
	reach := 0
	for i := 0; i < len(nums); i++ {
		if i > reach {
			return false // до этой клетки не добраться
		}
		if i+nums[i] > reach {
			reach = i + nums[i]
		}
		if reach >= len(nums)-1 {
			return true // ранний выход
		}
	}
	return true
}

// Jump — минимальное число прыжков до последнего индекса (LeetCode 45).
// Гарантировано, что добраться можно.
//
// Greedy «уровнями»: на каждом шаге обрабатываем ВСЁ, что достижимо
// с текущей позиции, и берём максимум дальше — это и есть следующий
// прыжок. То же, что BFS по «уровням прыжков», но за O(n).
//
// Пример: [2,3,1,1,4] -> 2 (0->1->4).
func Jump(nums []int) int {
	jumps := 0
	curEnd := 0   // граница текущего «уровня»
	farthest := 0 // самая дальняя клетка следующего уровня

	for i := 0; i < len(nums)-1; i++ { // последний индекс прыгать не надо
		if i+nums[i] > farthest {
			farthest = i + nums[i]
		}
		if i == curEnd { // текущий уровень исчерпан — прыгаем
			jumps++
			curEnd = farthest
		}
	}
	return jumps
}
